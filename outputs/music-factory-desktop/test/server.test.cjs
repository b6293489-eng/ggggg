'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');const os=require('node:os');const path=require('node:path');
const {startServer}=require('../server.cjs');
test('bridge authentication, account isolation, file ranges and CSRF',async t=>{
  const dataDir=fs.mkdtempSync(path.join(os.tmpdir(),'factory-server-test-'));
  const audio=path.join(dataDir,'a.wav');fs.writeFileSync(audio,Buffer.from('abcdefghijklmnop'));
  const calls=[];const factory={getState:()=>({tracks:[{id:'a',accountId:'bos'}],jobs:[{accountId:'bos',status:'running',trackIds:['a']}]}),audioPath:id=>{assert.equal(id,'a');return audio;},bridgeHeartbeat:id=>({ok:true,id}),claimJob:id=>({id:'j',accountId:id}),reportJob:(a,id,p)=>{calls.push({a,id,p});return {ok:true};}};
  let focused=0;
  const s=await startServer({factory,dataDir,uiDir:dataDir,port:0,onFocus:()=>{focused++;return {ok:true};},action:async(a,p)=>({a,p})});t.after(async()=>{await s.close();fs.rmSync(dataDir,{recursive:true});});
  const url=`http://127.0.0.1:${s.port}`;
  const bridge=(token,extra={})=>({Authorization:'Bearer '+token,'X-Music-Factory-Bridge-Version':'2.1.0','X-Music-Factory-Bridge-Revision':'playwright-primary-v1',...extra});
  assert.equal((await fetch(url+'/api/state')).status,401);
  assert.equal((await fetch(url+'/api/state',{headers:{Authorization:'Bearer '+s.token,Origin:'https://evil.example'}})).status,403);
  assert.equal((await fetch(url+'/api/state',{headers:{Authorization:'Bearer '+s.token}})).status,200);
  const bos=s.pairing.pair('bos').token,rivi=s.pairing.pair('rivi').token;
  assert.equal((await fetch(url+'/bridge/focus',{method:'POST'})).status,401);
  assert.equal((await fetch(url+'/bridge/focus',{method:'POST',headers:{Authorization:'Bearer '+bos}})).status,426);
  assert.equal((await fetch(url+'/bridge/focus',{method:'POST',headers:{Authorization:'Bearer '+bos,'X-Music-Factory-Bridge-Version':'2.1.2'}})).status,426);
  assert.equal((await fetch(url+'/bridge/focus',{method:'POST',headers:{Authorization:'Bearer '+bos,'X-Music-Factory-Bridge-Version':'2.0.0'}})).status,426);
  assert.equal((await fetch(url+'/bridge/focus',{method:'POST',headers:{Authorization:'Bearer '+bos,'X-Music-Factory-Bridge-Version':'3.0.0'}})).status,426);
  assert.equal(focused,0);
  assert.equal((await fetch(url+'/bridge/focus',{method:'POST',headers:bridge(bos)})).status,200);
  assert.equal(focused,1);
  assert.equal((await fetch(url+'/bridge/focus',{method:'POST',headers:bridge(bos,{'X-Music-Factory-Bridge-Version':'2.1.9'})})).status,200);
  assert.equal((await fetch(url+'/bridge/focus',{method:'POST',headers:bridge(bos,{'X-Music-Factory-Bridge-Version':'2.2.3'})})).status,200);
  assert.equal(focused,3);
  assert.equal((await fetch(url+'/bridge/job?accountId=rivi',{headers:bridge(bos)})).status,403);
  assert.equal((await fetch(url+'/bridge/audio/a',{headers:bridge(rivi)})).status,403);
  const range=await fetch(url+'/bridge/audio/a',{headers:bridge(bos,{Range:'bytes=3-7'})});
  assert.equal(range.status,206);assert.equal(range.headers.get('content-range'),'bytes 3-7/16');assert.equal(await range.text(),'defgh');
  assert.equal((await fetch(url+'/bridge/audio/a',{headers:bridge(bos,{Range:'bytes=20-30'})})).status,416);
  assert.equal((await fetch(url+'/bridge/report',{method:'POST',headers:bridge(bos,{'Content-Type':'application/json'}),body:JSON.stringify({jobId:'j',accountId:'rivi'})})).status,403);
  assert.equal(calls.length,0);
});
